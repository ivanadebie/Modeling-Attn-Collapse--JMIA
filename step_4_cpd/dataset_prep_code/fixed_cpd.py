import pandas as pd
import numpy as np
import ast

# Load the dataset
df = pd.read_csv('prepared_dataset_cpd (2).csv')
print(f"Loaded: {df.shape[0]} rows, {df.shape[1]} columns")
print(f"Columns: {list(df.columns)}")

# Check if sentence_level_hallu_scores column exists
if 'sentence_level_hallu_scores' in df.columns:
    print("Found sentence_level_hallu_scores - expanding...")

    expanded_rows = []
    for idx, row in df.iterrows():
        try:
            scores_dict = ast.literal_eval(row['sentence_level_hallu_scores'])
            for sent_idx, (sentence, score) in enumerate(scores_dict.items()):
                new_row = row.to_dict()
                new_row['sentence_text'] = sentence
                new_row['chunk_hallu_score'] = score
                new_row['chunk_index'] = sent_idx
                del new_row['sentence_level_hallu_scores']
                expanded_rows.append(new_row)
        except:
            continue

    df = pd.DataFrame(expanded_rows)
    print(f"Expanded to: {df.shape[0]} rows")
else:
    print("Column 'sentence_level_hallu_scores' not found - data may already be at chunk level")
    print("Current columns:", list(df.columns))

# Define index columns that should come first
index_cols = ['domain', 'question_id', 'sequence_id', 'row_index', 'config', 'config_idx', 'chunk_index']

# Get available index columns and other columns
available_idx = [c for c in index_cols if c in df.columns]
other_cols = [c for c in df.columns if c not in index_cols]

# Reorder
df = df[available_idx + other_cols]

print("New column order:")
for i, col in enumerate(df.columns):
    marker = "📍" if col in index_cols else "  "
    print(f"{marker} {i}: {col}")

# First, check what columns exist
print("Available columns:", list(df.columns))

# Extract config components
df['density_level'] = df['config'].apply(lambda x: x.split('-')[0])
df['interference_type'] = df['config'].apply(lambda x: x.split('-')[1])
df['evidence_pos_category'] = df['config'].apply(lambda x: x.split('-')[2])

# Distractor density
density_map = {'Low': 0.33, 'Medium': 0.67, 'High': 1.0}
df['distractor_density_chunk'] = df['density_level'].map(density_map)

# Evidence position encoded
pos_map = {'Beg': 0.0, 'Mid': 0.5, 'End': 1.0}
df['evidence_position_encoded'] = df['evidence_pos_category'].map(pos_map)

# Evidence overlap ratio (from cosine_similarity)
if 'cosine_similarity' in df.columns:
    min_sim, max_sim = df['cosine_similarity'].min(), df['cosine_similarity'].max()
    df['evidence_overlap_ratio'] = (df['cosine_similarity'] - min_sim) / (max_sim - min_sim) if max_sim > min_sim else 0.5
    df['evidence_overlap_emb'] = df['cosine_similarity']

# Create sequence_id if it doesn't exist (from row_index + config or question_id + config)
if 'sequence_id' not in df.columns:
    if 'row_index' in df.columns and 'config' in df.columns:
        df['sequence_id'] = df['row_index'].astype(str) + '_' + df['config']
    elif 'question_id' in df.columns and 'config' in df.columns:
        df['sequence_id'] = df['question_id'].astype(str) + '_' + df['config']
    print("Created sequence_id column")

# Normalized chunk index per sequence
if 'sequence_id' in df.columns and 'chunk_index' in df.columns:
    df['normalized_chunk_index'] = df.groupby('sequence_id')['chunk_index'].transform(
        lambda x: x / x.max() if x.max() > 0 else 0
    )
elif 'chunk_index' in df.columns:
    # Fallback: just normalize globally
    df['normalized_chunk_index'] = df['chunk_index'] / df['chunk_index'].max()

# Interference score
if 'is_gold_binary' in df.columns and 'cosine_similarity' in df.columns:
    df['interference_score_lexical_wrt_distractors'] = np.where(
        df['is_gold_binary'] == 0, 1 - df['cosine_similarity'], 0
    )

print("\nAdded derived features ✓")
print(df[['distractor_density_chunk', 'evidence_overlap_ratio']].describe())

# Fix evidence_overlap_ratio - use evid_overlap_emb as source
if 'evid_overlap_emb' in df.columns:
    df['evidence_overlap_ratio'] = df['evid_overlap_emb']
    df['evidence_overlap_emb'] = df['evid_overlap_emb']
    print("Fixed evidence_overlap_ratio from evid_overlap_emb ✓")
elif 'evid_overlap_ngram' in df.columns:
    df['evidence_overlap_ratio'] = df['evid_overlap_ngram']
    print("Fixed evidence_overlap_ratio from evid_overlap_ngram ✓")

# Check the fix
print("\nevidence_overlap_ratio stats:")
print(df['evidence_overlap_ratio'].describe())

print("\nKey columns check:")
key_cols = ['hallu_score', 'hallu_label', 'hallucination_label', 'hallucination_score',
            'evidence_overlap_ratio', 'distractor_density_chunk', 'att_avg_entropy',
            'cross_attention_mass_to_gold', 'distractor_attention_max']
for col in key_cols:
    if col in df.columns:
        non_null = df[col].notna().sum()
        print(f"  {col}: {non_null}/{len(df)} non-null")

# Define index columns that should come first
index_cols = ['domain', 'question_id', 'sequence_id', 'row_index', 'config', 'config_idx', 'chunk_index']

# Get available index columns and other columns
available_idx = [c for c in index_cols if c in df.columns]
other_cols = [c for c in df.columns if c not in index_cols]

# Reorder
df = df[available_idx + other_cols]

print("Reordered columns ✓")
print(f"\nFirst 10 columns (indices marked with 📍):")
for i, col in enumerate(df.columns[:10]):
    marker = "📍" if col in index_cols else "  "
    print(f"{marker} {i}: {col}")

# Save
output_file = 'prepared_dataset_cpd_fixed.csv'
df.to_csv(output_file, index=False)

print(f"\n✅ Saved to {output_file}")
print(f"Final shape: {df.shape[0]:,} rows × {df.shape[1]} columns")

# Summary of hallu columns
print(f"\n📊 Hallucination columns summary:")
print(f"  hallu_label (chunk-level): {df['hallu_label'].value_counts().to_dict()}")
print(f"  hallucination_label (response-level): {df['hallucination_label'].value_counts().to_dict()}")

print("=" * 70)
print("✅ VERIFICATION OF TASKS")
print("=" * 70)

# Task 1: Expand sentence_level_hallu_scores to chunk hallu scores
print("\n1️⃣ TASK: Expand sentence_level_hallu_scores to chunk hallu scores")
print("   (same as done for model_answer_chunk)")
if 'chunk_hallu_score' in df.columns or 'hallu_score' in df.columns:
    score_col = 'chunk_hallu_score' if 'chunk_hallu_score' in df.columns else 'hallu_score'
    print(f"   ✅ DONE - Column '{score_col}' exists at chunk level")
    print(f"   Stats: {df[score_col].describe()[['count','mean','min','max']].to_dict()}")
else:
    print("   ❌ NOT DONE - No chunk-level hallu score column found")

# Task 2: Reorder columns with indices first
print("\n2️⃣ TASK: Reorder columns (indices at start)")
index_cols = ['domain', 'question_id', 'sequence_id', 'row_index', 'config', 'config_idx', 'chunk_index']
first_cols = list(df.columns[:7])
indices_first = all(c in index_cols for c in first_cols if c in df.columns)
print(f"   First 7 columns: {first_cols}")
if indices_first:
    print("   ✅ DONE - Index columns are at the start")
else:
    print("   ❌ NOT DONE - Index columns not at start")

# Task 3: Fix evidence_overlap_ratio and evidence_overlap_emb
print("\n3️⃣ TASK: Fix evidence_overlap_ratio and evidence_overlap_emb (was empty)")
for col in ['evidence_overlap_ratio', 'evidence_overlap_emb', 'evid_overlap_emb']:
    if col in df.columns:
        non_null = df[col].notna().sum()
        print(f"   {col}: {non_null:,}/{len(df):,} non-null", "✅" if non_null > 0 else "❌")

# Task 4: Check hallu_label vs hallucination_label difference
print("\n4️⃣ INFO: hallu_label vs hallucination_label difference")
print("   hallu_label (chunk-level):")
print(f"      Values: {df['hallu_label'].value_counts().to_dict()}")
print("   hallucination_label (response-level):")
print(f"      Values: {df['hallucination_label'].value_counts().to_dict()}")
print("   ℹ️  Use 'hallu_label' for CPD (chunk-level signal)")

# Task 5: Check if hallucination_label has 1s now
print("\n5️⃣ TASK: Check why hallucination_label had no 1s in previous version")
has_ones = (df['hallucination_label'] == 1).sum()
print(f"   hallucination_label=1 count: {has_ones:,}")
if has_ones > 0:
    print("   ✅ Has hallucination labels = 1")
else:
    print("   ⚠️  All 0s - this is RESPONSE-level label, use hallu_label for chunk-level")

print("\n" + "=" * 70)
print("📁 OUTPUT FILE: prepared_dataset_cpd_fixed.csv")
print(f"📏 SHAPE: {df.shape[0]:,} rows × {df.shape[1]} columns")
print("=" * 70)

